"""关键词库 —— v1 规则版的核心资产。

设计意图
--------
招聘方在平台上"搜人"，搜的是**岗位相关的词**。求职者看不到这个词表，所以
本库就是把这个黑箱显式化：库里的词一旦出现在 JD 里，就说明招聘方（或平台
算法）大概率会拿它去找人。

分层
----
  title      职位名词 —— 招聘方搜人的第一入口，影响最大
  hard_skill 硬技能 / 核心能力词 —— JD 明确写出来的
  tool       工具与技术栈
  domain     领域与行业词
  soft       软性能力词（算法也会做字面匹配）
  bonus      加分词

necessity 判定（v1 启发式，不依赖模型）
--------------------------------------
  title / hard_skill          -> must（JD 写了就是门槛）
  tool / domain / soft / bonus -> nice（有更好，没有不致命）

为什么不用 LLM 判 necessity：v1 要的是**确定性和可复现**。任何一条"必需 /
加分"的判断都能对着 JD 原文复核，这是招聘场景的合规底线。v2 再接模型。
"""

